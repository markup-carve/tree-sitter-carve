// Writes src/unicode_words.h, the word characters of C2-I-127 (general
// category L or N), from the spec's data/unicode-categories.json:
//
//   node scripts/unicode-words.mjs <path to spec/0.2/data/unicode-categories.json>
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/unicode-words.mjs <unicode-categories.json>');
  process.exit(2);
}
const data = JSON.parse(readFileSync(source, 'utf8'));
const points = [];
for (const category of data.categories) {
  if (category.name !== 'L' && category.name !== 'N') continue;
  for (const range of category.ranges) {
    const [from, to = from] = range.split('-').map((hex) => parseInt(hex, 16));
    points.push([from, to]);
  }
}
points.sort((a, b) => a[0] - b[0]);
const runs = [];
for (const [from, to] of points) {
  const last = runs.at(-1);
  if (last && from <= last[1] + 1) last[1] = Math.max(last[1], to);
  else runs.push([from, to]);
}
const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const lines = [
  `// Unicode ${data.unicode} L and N (C2-I-127). Generated by scripts/unicode-words.mjs.`,
  `// Source: ${data.source} (sha256 ${data.source_sha256})`,
  'static const uint32_t carve_word_ranges[][2] = {',
  ...runs.map(([a, b]) => `  {${hex(a)}, ${hex(b)}},`),
  '};',
  '',
];
const target = fileURLToPath(new URL('../src/unicode_words.h', import.meta.url));
writeFileSync(target, lines.join('\n'));
console.log(`${runs.length} ranges -> ${target}`);
